#!/usr/bin/env python3

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def load(name: str):
    with open(os.path.join(HERE, name)) as fh:
        return json.load(fh)


def f(v, prec: int = 3, signed: bool = True) -> str:
    if v is None:
        return "-"
    return f"{v:+.{prec}f}" if signed else f"{v:.{prec}f}"


def p(v) -> str:
    if v is None:
        return "-"
    return f"{v:.4f}"


def table(header: list, rows: list) -> list:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(x) for x in r) + " |")
    return out


def ladder(rows: list) -> str:
    return " / ".join("(" + ", ".join(f"{x:g}" for x in r) + ")" for r in rows)


def render() -> str:
    proto = load("protocol.json")
    lock = load("protocol_lock.json")
    cov = load("coverage_report.json")
    checks = load("checks.json")
    arms = load("arm_validation.json")
    sel = load("selection.json")
    train = load("results_train.json")
    judge = load("results_judge.json")
    cont = load("continuous.json")
    verdict = load("verdict.json")
    log = load("scoring_log.json")
    L = []
    L.append("# mean_reversion exit ladder study (issue 2018)")
    L.append("")
    L.append("Generated by `render_report.py` from the persisted study files; it scores and fetches nothing. "
             "Every number below comes from `selection.json`, `results_*.json`, `continuous.json` and "
             "`verdict.json`. Paired numbers are percent of entry notional per opened position; continuous numbers "
             "are percent of the 1000 USD initial capital.")
    L.append("")
    L.append("## Verdict")
    L.append("")
    rows = []
    for ukey, u in sorted(verdict["units"].items()):
        why = []
        for arm, a in sorted(u["arms"].items()):
            if not a.get("judged"):
                continue
            why.append(f"`{arm}`: " + ("passes" if a["passes"] else "; ".join(a["fails"])))
        rows.append([f"`{ukey}`", f"**{u['verdict']}**", "<br>".join(why) or "no judged arm"])
    L += table(["unit (frame/group/direction)", "verdict", "reason per judged arm"], rows)
    L.append("")
    sugg = [u.get("suggested_config") for u in verdict["units"].values() if u.get("suggested_config")]
    if sugg:
        L.append("Suggested offline configs (suggest-only, not applied): " + ", ".join(f"`{s}`" for s in sorted(sugg))
                 + ".")
        L.append("")
        for ukey, u in sorted(verdict["units"].items()):
            if not u.get("suggested_arm"):
                continue
            g = u["arms"][u["suggested_arm"]]["continuous"]
            parts = []
            for cost, c in sorted(g["costs"].items()):
                parts.append(f"{cost} {f(c['candidate_pooled_return_pct'], 1)}% (incumbent "
                             f"{f(c['incumbent_pooled_return_pct'], 1)}%)")
            loss = all(c["candidate_net_pnl_usd"] < 0 for c in g["costs"].values())
            L.append(f"**Absolute result of `{ukey}`:** the suggested arm `{g['arm']}` returns " + ", ".join(parts)
                     + f" of the pooled initial capital over the continuous interval. "
                     + ("It still loses money at both costs: the gain is relative to the incumbent exit, and the "
                        "complete strategy is unprofitable under both exits." if loss else
                        "The absolute result is shown per dataset in the continuous section."))
    else:
        L.append("No unit is positive, so no suggested configuration is written. Fleet defaults, "
                 "`config.example.json`, registry defaults, quarantine status and `edge_status` are unchanged.")
    L.append("")
    L.append(f"Holm family: m = {verdict['family']['m']}, alpha {verdict['family']['alpha']}.")
    L.append("")
    L.append("## Question and boundary")
    L.append("")
    L.append(proto["question"])
    L.append("")
    L.append(proto["suggest_only"] + " " + proto["deployment_context"])
    L.append("")
    L.append("## Frames and arms")
    L.append("")
    for frame in sorted(proto["frames"]):
        fr = proto["frames"][frame]
        d = fr["arm_definitions"]
        L.append(f"### `{frame}`: {fr['label']}")
        L.append("")
        L.append(f"Direction `{fr['direction']}`. Groups: " + "; ".join(
            f"{g}: " + ", ".join(f"{c} {t}" for c, t in pairs) for g, pairs in sorted(fr["groups"].items())) + ".")
        L.append("")
        rows = [["incumbent ranging_volatile ladder", ladder(d["incumbent_volatile_ladder"])]]
        for arm in sorted(d["candidate_ladders"]):
            role = "primary" if arm == fr["paired"]["arms"]["primary"] else "neighbour"
            rows.append([f"`{arm}` ({role}, widening x{d['widening'][arm]:g})", ladder(d["candidate_ladders"][arm])])
        L += table(["arm", "ladder (ATR multiple, cumulative close fraction" +
                    (", trail after)" if frame == "ratchet" else ")")], rows)
        L.append("")
        if frame == "b2":
            L.append(d["paired_form"] + ". " + d["continuous_form"])
            L.append("")
            L.append("Changes from the 1152 history:")
            L.append("")
            for c in fr["changes_from_history"]:
                L.append(f"- {c}")
        else:
            L.append(d["relation_to_b2"])
            L.append("")
            L.append(d["incumbent_close"] + "; " + d["incumbent_trail"] + ".")
        L.append("")
        ch = arms["frames"][frame]["checks"]
        okc = sorted(k for k, v in ch.items() if isinstance(v, dict) and v.get("ok"))
        L.append(f"Resolver checks (`arm_validation.json`): {len(okc)} arm files pass the real Python resolver "
                 "comparison (only `ranging_volatile` differs from the defaults, every label keeps an exit, the stop "
                 "owner is unchanged); paired arms differ only in the close: "
                 f"{ch.get('paired_arms_differ_only_in_close')}.")
        if frame == "ratchet":
            fb = ch["directional_fallback"]
            L.append(f" A table with only the bare `ranging_directional` key serves `_up` and `_down`: "
                     f"{fb['bare_key_only_serves_sublabels']}.")
        L.append("")
    gi = arms["go_inspect"]
    L.append(f"`go-trader inspect --json --all` loads all {len(gi)} arm files with the close and regime trail "
             f"preserved: {all(v['ok'] for v in gi.values())}. For the unified B2 close, `inspect` prints the stop "
             "source as `max_drawdown_pct (fallback)`; `EffectiveStopLossPct` returns 0 for a unified close, whose "
             "per-regime `stop_loss_atr` owns the stop, so this is a display gap of `inspect` only.")
    L.append("")
    L.append("## Inputs and coverage")
    L.append("")
    L.append(proto["inputs"]["note"])
    L.append("")
    rows = []
    for r in cov["rows"]:
        c = r.get("candles") or {}
        fu = r.get("funding") or {}
        rows.append([r["group"], f"{r['coin']} {r['interval']}", r["window"], r["status"],
                     c.get("first_bar", "-"), c.get("last_bar", "-"), c.get("missing_bars", "-"),
                     fu.get("venue_absent_hours", "-"), r["reason"]])
    L += table(["group", "dataset", "window", "status", "first scored bar", "last scored bar", "missing candles",
                "venue-absent funding hours", "reason"], rows)
    L.append("")
    L.append("Costs: " + proto["costs"]["text"] + " " + proto["funding"]["treatment"] + " "
             + proto["funding"]["coverage_rule"])
    L.append("")
    L.append("## Protocol, lock and scoring order")
    L.append("")
    w = proto["windows"]
    L.append(f"Windows (half-open, UTC): train {w['train']['start']} to {w['train']['end']}; judge "
             f"{w['judge']['start']} to {w['judge']['end']}; continuous {w['continuous']['start']} to "
             f"{w['continuous']['end']}; native tails "
             + ", ".join(f"{k} {v[0]} to {v[1]}" for k, v in sorted(proto["native"]["windows"].items())) + ". "
             + proto["initial_state"])
    L.append("")
    L.append(f"Lock: `protocol_lock.json` written {lock['locked_at_utc']}, protocol sha256 "
             f"`{lock['protocol_sha256'][:16]}`, {len(lock['files_sha256'])} locked files and "
             f"{len(lock['code_sha256'])} code files hashed; revisions: {len(lock.get('revisions') or [])}.")
    L.append("")
    rows = []
    for e in log["events"]:
        rows.append([e["command"], e["started_utc"], e.get("finished_utc", "-"), f"`{e['lock_commit'][:12]}`",
                     f"`{e['head'][:12]}`", e.get("guarded_unchanged", "-"), e.get("network_calls", "-"),
                     "yes" if e.get("first_scoring") else ""])
    L += table(["command", "started", "finished", "lock commit", "head", "shared files unchanged",
                "refused network calls", "first scoring"], rows)
    L.append("")
    st = proto["statistics"]
    L.append(f"Statistics: {st['test']}; {st['blocks']}; {st['synchronization']}; seed {st['seed']}, "
             f"{st['resamples']} resamples. Harm: {st['dataset_harm']}. Family: {st['family']} Floors: "
             + ", ".join(f"{k} {v}" for k, v in sorted(st["sample_floors"].items())) + ".")
    L.append("")
    L.append("## Training selection")
    L.append("")
    rows = []
    for frame, s in sorted(sel["frames"].items()):
        for arm, sc in sorted(s["scores"].items()):
            rows.append([frame, f"`{arm}`", sc["matched_positions"], f(sc["pooled_mean_delta_pct"], 4),
                         "judged" if arm in s["judged"] else "unjudged"])
    L += table(["frame", "arm", "matched positions (train, base)", "pooled mean delta %", "role"], rows)
    L.append("")
    L.append(proto["selection"]["rule"])
    L.append("")
    tr = []
    for uid, u in sorted(train["units"].items()):
        sch = u["schedule"]
        tr.append([u["unit"]["frame"], f"{u['unit']['coin']} {u['unit']['interval']}", sch["positions"],
                   sch["close_records"], sch["long_positions"], sch["short_positions"],
                   min(a["base"]["matched"] for a in u["arms"].values()),
                   u["range"]["scored_first_bar"], u["range"]["scored_last_bar"]])
    L += table(["frame", "dataset", "scheduled positions", "close records (free run)", "long", "short",
                "min matched over arms", "first bar", "last bar"], tr)
    L.append("")
    L.append("## Paired attribution (judgment)")
    L.append("")
    for ukey, u in sorted(verdict["units"].items()):
        L.append(f"### `{ukey}`")
        L.append("")
        rows = []
        for arm, a in sorted(u["arms"].items()):
            if not a.get("judged"):
                rows.append([f"`{arm}`", "-", "unjudged", "-", "-", "-", "-", "-", "-", "-"])
                continue
            for cost, c in sorted(a["costs"].items()):
                rows.append([f"`{arm}`", cost, f"{c['matched']}/{c['scheduled']}", f(c["match_coverage"], 3, False),
                             c["effective_blocks"], f(c["incumbent_mean_net_pct"]), f(c["candidate_mean_net_pct"]),
                             f(c["mean_delta_pct"], 4), p(c["p_improve"]), ", ".join(c["harmed"]) or "none"])
        L += table(["arm", "cost", "matched/scheduled", "coverage", "effective blocks", "incumbent net %",
                    "candidate net %", "mean delta %", "p (improve)", "significant negative"], rows)
        L.append("")
        for arm, a in sorted(u["arms"].items()):
            if not a.get("judged"):
                continue
            L.append(f"`{arm}`: decision p {p(a['decision_p'])}, Holm threshold {p(a['holm']['threshold'])}, "
                     f"rejected {a['holm']['rejected']}.")
            L.append("")
            rows = []
            for cost, c in sorted(a["costs"].items()):
                for ds, d in sorted(c["datasets"].items()):
                    rows.append([cost, ds, f"{d['matched']}/{d['scheduled']}", f(d["incumbent_mean_net_pct"]),
                                 f(d["candidate_mean_net_pct"]), f(d["mean"], 4)])
                for side, s in sorted(c["sides"].items()):
                    if s["n"]:
                        rows.append([cost, f"side {side}", s["n"], "-", "-", f(s["mean"], 4)])
            L += table(["cost", "dataset or side", "matched", "incumbent net %", "candidate net %",
                        "mean delta %"], rows)
            L.append("")
            harm_rows = []
            for cost, c in sorted(a["costs"].items()):
                for k, h in sorted(c["harm"].items()):
                    if h.get("tested"):
                        harm_rows.append([cost, k, h["n"], f(h["mean"], 4), p(h["p"]),
                                          p(h["holm"]["threshold"]), h["holm"]["rejected"]])
            if harm_rows:
                L += table(["cost", "harm test", "n", "mean delta %", "p (harm)", "Holm threshold", "rejected"],
                           harm_rows)
                L.append("")
    jrows = []
    for uid, u in sorted(judge["units"].items()):
        a0 = next(iter(u["arms"].values()))
        jrows.append([u["unit"]["frame"], u["unit"]["group"], f"{u['unit']['coin']} {u['unit']['interval']}",
                      u["schedule"]["positions"], u["schedule"]["close_records"],
                      sum(len(c["unmatched"]) for a in u["arms"].values() for c in a.values()),
                      sum(c["censored"] for a in u["arms"].values() for c in a.values()),
                      u["range"]["scored_first_bar"], u["range"]["scored_last_bar"]])
    L.append("Judged units (incumbent free-run schedule at base cost):")
    L.append("")
    L += table(["frame", "group", "dataset", "scheduled positions", "close records", "unmatched replays (all arms)",
                "censored at window end (all arms)", "first bar", "last bar"], jrows)
    L.append("")
    L.append("## Continuous complete-policy runs")
    L.append("")
    L.append(proto["continuous_rule"]["metrics"] + ". " + proto["continuous_rule"]["terminal"] + ". "
             + proto["return_denominator"] + ".")
    L.append("")
    for key, by_arm in sorted(verdict["continuous"].items()):
        L.append(f"### `{key}`")
        L.append("")
        rows = []
        for arm, by_cost in sorted(by_arm.items()):
            for cost, by_ds in sorted(by_cost.items()):
                for ds, m in sorted(by_ds.items()):
                    rows.append([f"`{arm}`", cost, ds, f(m["return_pct"], 2), f(m["sharpe_daily"], 2),
                                 f(m["worst_drawdown_pct"], 2), m["positions"], m["close_records"],
                                 f(m["fees_usd"], 2, False), f(m["funding_usd"], 2), f(m["terminal_settlement_usd"], 2),
                                 m["reconciled"], f"{m['first_bar']} to {m['last_bar']}"])
        L += table(["arm", "cost", "dataset", "return %", "Sharpe (daily)", "worst drawdown %", "positions",
                    "close records", "fees USD", "funding USD", "terminal settlement USD", "reconciled",
                    "range"], rows)
        L.append("")
        unit = next((u for k, u in verdict["units"].items() if k.startswith(key + "/")), None)
        if unit:
            for arm, a in sorted(unit["arms"].items()):
                if not a.get("judged"):
                    continue
                g = a["continuous"]
                parts = []
                for cost, c in sorted(g.get("costs", {}).items()):
                    parts.append(f"{cost}: candidate {f(c['candidate_net_pnl_usd'], 2)} USD "
                                 f"({f(c['candidate_pooled_return_pct'], 2)}%) vs incumbent "
                                 f"{f(c['incumbent_net_pnl_usd'], 2)} USD ({f(c['incumbent_pooled_return_pct'], 2)}%) "
                                 f"on {c['denominator_usd']:g} USD")
                L.append(f"Gate for `{arm}` ({g['arm']}): {'pass' if g['pass'] else 'fail'}. " + "; ".join(parts)
                         + (f". {g['why']}" if g["why"] else "") + ".")
                L.append("")
    eq = verdict.get("equivalence", {})
    for frame, e in sorted(eq.items()):
        L.append(f"Equivalence (`{frame}`): the historical scalar-stop incumbent and the unified incumbent trade "
                 f"identically in every continuous run and cost: {e['all_identical']} ({len(e['rows'])} runs).")
        L.append("")
    L.append("## Checks")
    L.append("")
    rows = [[k, "ok" if v.get("ok") else "FAIL"] for k, v in sorted(checks["cases"].items())]
    L += table(["pre-lock check (`checks.json`, parity window 2023-01-01 to 2023-07-01)", "result"], rows)
    L.append("")
    vr = checks["cases"]["verdict_rules"]["cases"]
    L.append("Verdict-rule cases through the real decision function: " + "; ".join(
        f"{k} {v['got']}" if isinstance(v, dict) else f"{k} {v}" for k, v in sorted(vr.items())) + ".")
    L.append("")
    if os.path.exists(os.path.join(HERE, "checks_post.json")):
        post = load("checks_post.json")
        L.append("Post-scoring checks (`checks_post.json`): " + ", ".join(
            f"{k} {'ok' if v.get('ok', True) else 'FAIL'}" for k, v in sorted(post["cases"].items())) + ".")
        L.append("")
    L.append("## Prior inspection and limits")
    L.append("")
    for x in proto["prior_inspection"] + proto["disclosures"]:
        L.append(f"- {x}")
    L.append(f"- {proto['direction_handling']['b2']}")
    L.append(f"- {proto['open_strategy']['short_semantics']}")
    L.append("- A regime-isolated paired replay measures the exit change on the incumbent's gated entry schedule; "
             "it is not the return of the complete strategy. The continuous runs give that return and keep entries "
             "in every regime.")
    L.append("- A relative improvement does not establish absolute profitability; the continuous tables show the "
             "absolute result of each policy.")
    L.append("")
    return "\n".join(L) + "\n"


def main() -> None:
    text = render()
    with open(os.path.join(HERE, "REPORT.md"), "w") as fh:
        fh.write(text)
    print("wrote REPORT.md")


if __name__ == "__main__":
    main()
